"""The shipped alternate ruleset bundles: iso-24495 and asd-ste100.

Each bundle is data plus its own deterministic scorer with the same CLI
contract as the vendored FAA scorer. The service picks the bundle scorer
automatically when RULESET_PATH selects a bundle that carries one. The
golden scores below were generated by each bundle's own scorer and are
pinned here: if one of these fails, the bundle changed.
"""

import json
import subprocess
import sys
from pathlib import Path

import pytest

from plain_language_desk.ruleset import Ruleset, current, ruleset_path
from plain_language_desk.scorer import score_text

SRC = Path(__file__).resolve().parents[1] / "src" / "plain_language_desk"
BUNDLES = SRC / "rulesets"
ISO = BUNDLES / "iso-24495"
STE = BUNDLES / "asd-ste100"
DIN = BUNDLES / "din-8581"
ALL_BUNDLES = [(ISO, "ISO-R", "iso-24495"), (STE, "STE-", "asd-ste100"),
               (DIN, "DIN-R", "din-8581")]

GOLDENS = {
    ISO: {"clean.md": 100, "mid.md": 76, "bad.md": 49},
    STE: {"clean.md": 100, "mid.md": 86, "bad.md": 54},
    DIN: {"clean.md": 100, "mid.md": 91, "bad.md": 51},
}

# "shall" is an FAA-only violation (WS-04); neither alternate standard flags it.
SHALL_TEXT = "The operator shall review the report before the meeting starts."
# One semicolon is an STE violation (Rule 8.1 bans the mark outright); the
# FAA/ISO layer only objects at three or more in one sentence.
SEMICOLON_TEXT = "The check compares two digests; the values must match."
# German Vorgangspassiv: the DIN bundle flags it; the English-only layers
# have no German passive detector and let it pass.
GERMAN_PASSIVE_TEXT = "Es wird eine Prüfung durchgeführt."


@pytest.mark.parametrize("bundle,prefix,ref", ALL_BUNDLES)
def test_bundle_loads_with_expected_identity(bundle, prefix, ref):
    rs = Ruleset(bundle)
    assert rs.id == bundle.name
    assert rs.version == "1.0.0"
    assert rs.bar == 80
    assert rs.scorer_path is not None and rs.scorer_path.exists()


@pytest.mark.parametrize("bundle,prefix,ref", ALL_BUNDLES)
def test_bundle_carries_standard_prompts_and_goldens(bundle, prefix, ref):
    assert (bundle / "RULESET.md").exists()
    for name in ("clean.md", "mid.md", "bad.md"):
        assert (bundle / "golden" / name).exists()
    for name in ("rewrite-prompt-full.txt", "rewrite-prompt-minimal.txt"):
        prompt = (bundle / name).read_text()
        assert len(prompt) > 400
        # The prompt names the bundle's own rule prefix so findings read back.
        assert prefix in prompt


@pytest.mark.parametrize("bundle,prefix,ref", ALL_BUNDLES)
def test_bundle_scorer_is_deterministic(bundle, prefix, ref):
    golden = bundle / "golden" / "mid.md"
    runs = [json.loads(subprocess.run(
        [sys.executable, str(bundle / "scorer.py"), "--file", str(golden), "--json"],
        capture_output=True, text=True, check=True).stdout)["files"][0]["score"]
        for _ in range(2)]
    assert runs[0] == runs[1] == GOLDENS[bundle]["mid.md"]


@pytest.mark.parametrize("bundle", [ISO, STE], ids=["iso-24495", "asd-ste100"])
def test_golden_scores_match_the_bundle(bundle):
    for golden, expected in GOLDENS[bundle].items():
        out = subprocess.run(
            [sys.executable, str(bundle / "scorer.py"), "--file", str(bundle / "golden" / golden), "--json"],
            capture_output=True, text=True, check=True)
        got = json.loads(out.stdout)["files"][0]["score"]
        assert got == expected, f"{bundle.name}/{golden}: scorer says {got}, bundle pins {expected}"


@pytest.mark.asyncio
async def test_score_text_routes_to_the_bundle_scorer(monkeypatch):
    monkeypatch.setenv("RULESET_PATH", str(STE))
    report = await score_text(SEMICOLON_TEXT, current().scorer_path)
    assert report["version"] == "STE/1.0"
    assert {f["rule"] for f in report["findings"]} & {"STE-02"}
    # findings carry the same contract shape as the FAA scorer
    f = report["findings"][0]
    assert {"rule", "deduction", "line", "evidence"} <= set(f)


@pytest.mark.asyncio
async def test_the_same_text_scores_differently_under_different_standards(monkeypatch):
    monkeypatch.setenv("RULESET_PATH", str(STE))
    ste = await score_text(SHALL_TEXT, current().scorer_path)
    monkeypatch.setenv("RULESET_PATH", str(ISO))
    iso = await score_text(SHALL_TEXT, current().scorer_path)
    assert ste["score"] == 100 and iso["score"] == 100  # neither flags "shall"

    monkeypatch.setenv("RULESET_PATH", str(STE))
    ste_semi = await score_text(SEMICOLON_TEXT, current().scorer_path)
    monkeypatch.setenv("RULESET_PATH", str(ISO))
    iso_semi = await score_text(SEMICOLON_TEXT, current().scorer_path)
    assert ste_semi["score"] < iso_semi["score"]  # one semicolon: STE objects, ISO does not


def test_bare_ruleset_name_resolves_to_the_shipped_bundle(monkeypatch):
    monkeypatch.setenv("RULESET_PATH", "asd-ste100")
    assert ruleset_path() == STE
    assert current().ref == "asd-ste100@1.0.0"
    monkeypatch.setenv("RULESET_PATH", "din-8581")
    assert ruleset_path() == DIN
    assert current().ref == "din-8581@1.0.0"


def test_bare_ruleset_name_that_matches_nothing_stays_relative(monkeypatch, tmp_path):
    monkeypatch.chdir(tmp_path)
    monkeypatch.setenv("RULESET_PATH", "not-a-bundle")
    with pytest.raises(FileNotFoundError):
        current()


def test_faa_bundle_ships_no_scorer_of_its_own():
    rs = Ruleset(BUNDLES / "faa-plain-language")
    assert rs.scorer_path is None  # the vendored FAA scorer applies


@pytest.mark.parametrize("bundle,marker", [
    (ISO, "may have failed"),
    (STE, "may have failed"),
    (DIN, "könnte gescheitert sein"),
], ids=["iso-24495", "asd-ste100", "din-8581"])
def test_prompts_preserve_modality(bundle, marker):
    assert marker in (bundle / "rewrite-prompt-full.txt").read_text()


@pytest.mark.asyncio
async def test_the_german_passive_only_the_din_bundle_flags(monkeypatch):
    monkeypatch.setenv("RULESET_PATH", str(DIN))
    din = await score_text(GERMAN_PASSIVE_TEXT, current().scorer_path)
    monkeypatch.setenv("RULESET_PATH", str(ISO))
    iso = await score_text(GERMAN_PASSIVE_TEXT, current().scorer_path)
    assert din["score"] < iso["score"]
    assert {f["rule"] for f in din["findings"]} & {"DIN-R4"}
    assert iso["score"] == 100  # the English layers have no German detector
