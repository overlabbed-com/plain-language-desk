"""Parity between the vendored scorer and the Mac-side original.

The goldens were generated by the Mac scorer (md5 9cbd5f9ae97b5b16635efcf2cf92158d,
2026-10-31). If one of these fails, the scorer changed: re-vendor the copy,
regenerate the goldens, and refresh the bundle prompts in the same PR.
The vendor file is additionally pinned by sha256 so an accidental edit fails
before any score assertion can drift.
"""

import hashlib
import json
import subprocess
import sys
from pathlib import Path

VENDOR = (
    Path(__file__).resolve().parents[1] / "src" / "plain_language_desk" / "vendor" / "dsh-writing-score.py"
)
GOLDEN_DIR = (
    Path(__file__).resolve().parents[1] / "src" / "plain_language_desk" / "rulesets" / "faa-plain-language" / "golden"
)

VENDOR_SHA256 = "2329248ae06938fa9819fcc7095921471145e45bcf780736b1f731328ca7b2fb"
GOLDENS = {
    "clean.md": 95,
    "mid.md": 57,
    "bad.md": 29,
}


def test_vendor_file_is_sha256_pinned():
    digest = hashlib.sha256(VENDOR.read_bytes()).hexdigest()
    assert digest == VENDOR_SHA256, (
        "vendored scorer changed; re-verify against the original, re-pin the hash, "
        "and refresh the bundle prompts in the same PR"
    )


def run_vendored(path: Path) -> dict:
    proc = subprocess.run(
        [sys.executable, str(VENDOR), "--file", str(path), "--json"],
        capture_output=True,
        text=True,
        timeout=60,
    )
    assert proc.returncode == 0, f"vendored scorer failed: {proc.stderr[:300]}"
    return json.loads(proc.stdout)


def test_vendored_scorer_self_reports_pinned_version():
    data = run_vendored(GOLDEN_DIR / "clean.md")
    assert data["version"] == "WPS/1.1"


def test_golden_scores_match_the_mac_original():
    for name, expected in GOLDENS.items():
        data = run_vendored(GOLDEN_DIR / name)
        f = data["files"][0]
        assert f["score"] == expected, f"{name}: vendored {f['score']} != mac golden {expected}"


def test_vendored_copy_produces_the_pinned_report_shape():
    data = run_vendored(GOLDEN_DIR / "mid.md")
    f = data["files"][0]
    assert f["score"] == 57
    assert len(f["findings"]) == 18
    assert set(f) >= {"file", "score", "doc_words", "avg_sentence_words", "findings", "version"}
